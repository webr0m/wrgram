const fold=(value:string)=>value.toLowerCase().normalize('NFD').replace(/\p{Diacritic}/gu,'');
export const SKIN_TONES=['','🏻','🏼','🏽','🏾','🏿'];
const bare=(emoji:string)=>emoji.replace(/\uFE0F/g,'');
export function hasTone(emoji:string){return !!TONED[bare(emoji)];}
export function tonedEmoji(emoji:string,tone:number){const values=TONED[bare(emoji)];return tone>0&&values?values[tone-1]??emoji:emoji;}
export function findEmojis(query:string,group:number){
  const normalized=fold(query).trim();
  if(!normalized)return [...(EMOJI_GROUPS[group]??EMOJI_GROUPS[0]).items];
  const seen=new Set<string>(),result:string[]=[];
  for(const category of EMOJI_GROUPS){
    const categoryMatch=fold(`${category.name} ${category.words}`).includes(normalized);
    for(const emoji of category.items){
      if(!categoryMatch&&!(KEYWORDS[emoji]&&fold(KEYWORDS[emoji]).includes(normalized)))continue;
      if(!seen.has(emoji)){seen.add(emoji);result.push(emoji);}
    }
  }
  return result;
}
